export const DEFAULT_PROJECT_STAGE_TREE: ProjectStageBranch[] = CONSTRUCTION_STAGES.map((cat, cIdx) => ({
  id: cat.id,
  name: cat.name,
  iconName: cat.iconName,
  status: "pending",
  progress: 0,
  subStages: cat.subStages.map((sub, sIdx) => ({
    id: `${cat.id}_sub_${sIdx + 1}`,
    name: sub,
    code: `${cIdx + 1}.${sIdx + 1}`,
    status: "pending",
    progress: 0
  }))
}));

const GLOBAL_STAGE_TREE_STORAGE_KEY = "hesabdar_global_stage_tree_v2";

export function getSavedGlobalStageTree(): ProjectStageBranch[] {
  if (typeof window === "undefined") return DEFAULT_PROJECT_STAGE_TREE;
  try {
    const raw = window.localStorage.getItem(GLOBAL_STAGE_TREE_STORAGE_KEY);
    if (!raw) return DEFAULT_PROJECT_STAGE_TREE;
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) return parsed;
  } catch (e) {
    console.error("Failed to read global stage tree", e);
  }
  return DEFAULT_PROJECT_STAGE_TREE;
}

export function saveGlobalStageTree(tree: ProjectStageBranch[]): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(GLOBAL_STAGE_TREE_STORAGE_KEY, JSON.stringify(tree));
  } catch (e) {
    console.error("Failed to save global stage tree", e);
  }
}

export function getProjectEffectiveStageTree(project?: { stageTree?: ProjectStageBranch[]; customStages?: string[] } | null): ProjectStageBranch[] {
  if (project?.stageTree && Array.isArray(project.stageTree) && project.stageTree.length > 0) {
    return project.stageTree;
  }
  const baseTree = getSavedGlobalStageTree();
  if (project?.customStages && project.customStages.length > 0) {
    const existingNames = new Set<string>();
    baseTree.forEach((b) => {
      existingNames.add(b.name);
      b.subStages.forEach((s) => existingNames.add(s.name));
    });
    const extraSubs = project.customStages
      .filter((st) => st && !existingNames.has(st))
      .map((st, idx) => ({
        id: `custom_sub_${idx + 1}`,
        name: st,
        code: `سفارشی.${idx + 1}`,
        status: "pending" as const,
        progress: 0
      }));
    if (extraSubs.length > 0) {
      return [
        ...baseTree,
        {
          id: "stage_custom",
          name: "سایر مراحل اختصاصی پروژه",
          iconName: "Layers",
          status: "pending",
          progress: 0,
          subStages: extraSubs
        }
      ];
    }
  }
  return baseTree;
}

export function flattenStageTreeToStrings(tree: ProjectStageBranch[]): string[] {
  const result: string[] = [];
  for (const branch of tree) {
    for (const sub of branch.subStages || []) {
      if (sub.name && !result.includes(sub.name)) {
        result.push(sub.name);
      }
    }
  }
  return result;
}

